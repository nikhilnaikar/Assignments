import {expect, test} from '@playwright/test'

test("Add to Cart", async({page})=>
{
    await page.goto("https://www.decathlon.in/",{waitUntil:"domcontentloaded"})
    await expect(page).toHaveURL("https://www.decathlon.in/")
    await expect(page).toHaveTitle("Buy Sporting Goods, Sportswear and Equipments | Download App")
    const searchbox=page.locator('//input[@enterkeyhint="search"]')
    await expect(searchbox).toBeEnabled()
    await searchbox.click()
    await searchbox.fill("Shoes")
    await page.locator('//ul[@class="m-0 list-none p-0"]//span[text()="Running"]').click()
    await expect(page).toHaveTitle("Buy Running Shoes Online at Best Prices | Decathlon")
    //await page.waitForTimeout(8000)
    await page.waitForLoadState('networkidle')
    const sportFilter= page.locator('//span[@data-test-id="title:Sport"]')
    await sportFilter.waitFor({state:'visible'})
    await sportFilter.click()
    const runningFilter= page.locator('//input[@data-test-id="filter-checkbox-sport_pratice_en-Running"]')
    await runningFilter.waitFor({state:'visible'})
    await runningFilter.click()
    await page.locator('//span[@data-test-id="title:Gender"]').click()
    await page.locator('//input[@data-test-id="filter-checkbox-gender_id_en-MEN"]').click()
    await page.locator('//span[@data-test-id="title:Size"]').click()
    const sizeFilter= page.locator('//input[@data-test-id="filter-checkbox-indian_size-11"]')
    await sizeFilter.waitFor({state:'visible'})
    await sizeFilter.click({force:true})
    await page.locator('//div[@data-test-id="category-products-grid"]/div[1]').click()
    await page.locator('//span[@data-test-id="pdp-size-option-text-6"]').click()
    await page.locator('//button[@data-test-id="pdp:add-to-cart-button"]').click()
    //await page.waitForTimeout(16000)
    await page.locator('//div[@aria-label="Close"]').click()
    await page.locator('//a[@aria-label="Cart"]').click()
    const locator= page.locator('//span[text()="Men Running High Energy Return Shoes, Kiprun Kipcore - Grey"]')
    await expect(locator).toBeAttached()
    await page.pause()
})